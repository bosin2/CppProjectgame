// 아스키아트 + 구분선 + 대사를 출력하고 Enter 대기
void drawScene(string art[], int artC, string txt) {
    cout << CLEAR;

    cout << "\n";

    for (int i = 0; i < artC; i++)
        cout << art[i] << "\n";

    for (int i = 0; i < 50; i++) cout << "─";
    cout << "\n";

    cout << "\n\n";

    cout << txt << "\n";

    cout << "\n\n";

    cout << "➤ Enter ";

    cin.get();
}

